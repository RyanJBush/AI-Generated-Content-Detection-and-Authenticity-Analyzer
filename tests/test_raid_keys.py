"""CA1 prerequisite, independent of RAID data, tokenizers and models."""

import hashlib

import pytest

from litmus.data_prep.keys import ROW, SELECT, SPLIT, key, split_digest, split_source


@pytest.mark.parametrize(
    "tag,golden",
    [
        (SELECT, "8f0b8d7debfc008fe374190a50619c404b837f000998119452fc161416b859a8"),
        (SPLIT, "2ea3b192a8a6d022435e38a7eef2a7efaa22629d3044371e9f93c0589bac023b"),
        (ROW, "dd955a1ae74e0a7f54a5641ebb3fcf5f4266d9bcff5a46c620c471007671cbf7"),
    ],
)
def test_literal_encoding_golden(tag, golden):
    # Independent literal byte oracle; not generated by the function under test.
    literal = ('["' + tag + '",20261030,"source-0001"]').encode("utf-8")
    assert key(tag, 20261030, "source-0001") == hashlib.sha256(literal).digest()
    assert key(tag, 20261030, "source-0001").hex() == golden


def test_domain_separation_and_unambiguous_unicode_encoding():
    assert len({key(t, 20261030, "x") for t in (SELECT, SPLIT, ROW)}) == 3
    assert key(SELECT, 1, "23") != key(SELECT, 12, "3")
    assert key("ab", 0, "c") != key("a", 0, "bc")
    expected = '["litmus/r1/row/v1",0,"\u00e9"]'.encode("utf-8")
    assert key(ROW, 0, "\u00e9") == hashlib.sha256(expected).digest()


@pytest.mark.parametrize("seed,item", [(True, "a"), (1.0, "a"), (1, 23)])
def test_key_types(seed, item):
    with pytest.raises(TypeError):
        key(SELECT, seed, item)


def test_split_boundaries():
    assert split_digest(bytes(32)) == "dev"
    assert split_digest(bytes([255]) * 32) == "test"
    threshold = int(0.3 * 2**64)
    assert split_digest((threshold - 4096).to_bytes(8, "big") + bytes(24)) == "dev"
    assert split_digest(threshold.to_bytes(8, "big") + bytes(24)) == "test"


def test_selected_synthetic_sources_have_independent_split():
    sources = [str(i) for i in range(100000)]
    ordered = sorted(sources, key=lambda s: (key(SELECT, 20261030, s), s))
    selected = ordered[:1000]
    count = sum(split_source(20261030, s) == "dev" for s in selected)
    assert 240 <= count <= 360
    shuffled = sorted(reversed(sources), key=lambda s: (key(SELECT, 20261030, s), s))
    assert shuffled == ordered
