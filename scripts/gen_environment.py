"""Generate docs/environment.md (R0.6).

Run with the project interpreter so package versions come from the venv:
    .venv\\Scripts\\python.exe scripts\\gen_environment.py

Every value is read from the machine at run time. A lookup that fails is
written as "unavailable" with the reason; nothing is estimated.
"""
import datetime
import importlib.metadata
import pathlib
import platform
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "environment.md"


def _run(cmd):
    """Return (ok, text) for a command; text is stdout or the failure reason."""
    exe = shutil.which(cmd[0])
    if exe is None:
        return False, f"`{cmd[0]}` not found on PATH"
    try:
        proc = subprocess.run([exe, *cmd[1:]], capture_output=True, text=True,
                              timeout=30)
    except (OSError, subprocess.TimeoutExpired) as e:
        return False, f"{type(e).__name__}: {e}"
    if proc.returncode != 0:
        err = (proc.stderr or proc.stdout).strip().splitlines()
        first = err[0] if err else "(no output)"
        return False, f"exit {proc.returncode}: {first}"
    return True, proc.stdout.strip()


def _packages():
    rows = []
    for dist in importlib.metadata.distributions():
        name = dist.metadata["Name"]
        if name:
            rows.append((name.lower(), name, dist.version))
    return [(name, version) for _, name, version in sorted(rows)]


def _value(ok, text):
    return text if ok else f"unavailable ({text})"


def main() -> None:
    now = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    docker_cli = _run(["docker", "--version"])
    docker_engine = _run(["docker", "version", "--format", "{{.Server.Version}}"])
    gpu = _run(["nvidia-smi", "--query-gpu=name,driver_version,memory.total",
                "--format=csv,noheader"])

    try:
        import c2pa
        c2pa_native = c2pa.sdk_version()
    except Exception as e:
        c2pa_native = f"unavailable ({type(e).__name__}: {e})"

    lines = [
        "# Environment record",
        "",
        "Generated by `scripts/gen_environment.py`; do not edit by hand.",
        "",
        f"- Generated: {now}",
        "",
        "## Operating system",
        "",
        f"- Platform: {platform.platform()}",
        f"- System / release / version: {platform.system()} / "
        f"{platform.release()} / {platform.version()}",
        f"- Machine: {platform.machine()}",
        "",
        "## Python",
        "",
        f"- Version: {platform.python_version()} ({platform.python_implementation()})",
        f"- Build: {sys.version.splitlines()[0]}",
        f"- In virtual environment: {sys.prefix != sys.base_prefix}",
        "",
        "## Packages in the interpreter environment",
        "",
        "| Package | Version |",
        "|---|---|",
        *[f"| {name} | {version} |" for name, version in _packages()],
        "",
        f"- c2pa native SDK (`c2pa.sdk_version()`): {c2pa_native}",
        "",
        "## Docker",
        "",
        f"- CLI: {_value(*docker_cli)}",
        f"- Engine (server) version: {_value(*docker_engine)}",
        "",
        "## GPU / driver (optional metadata, via nvidia-smi)",
        "",
    ]
    if gpu[0]:
        lines += ["| name | driver_version | memory.total |", "|---|---|---|"]
        lines += [f"| {' | '.join(p.strip() for p in row.split(','))} |"
                  for row in gpu[1].splitlines()]
    else:
        lines.append(f"- unavailable ({gpu[1]})")
    lines.append("")

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
